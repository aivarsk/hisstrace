#!/usr/bin/env python3
"""Generate src/hisstrace/table.py from installed kernel unistd headers.

Syscall number/name tables come from the kernel headers. Argument names come
from the kernel's include/linux/syscalls.h prototypes (fetched, not installed),
falling back to arg0..arg5 at runtime for whatever is missing.
"""
import re
import urllib.request
from pathlib import Path

INT = re.compile(r"^#define __NR(?:3264)?_(\w+) (\d+)")
ALIAS = re.compile(r"^#define __NR_(\w+) __NR3264_(\w+)")
SYSCALLS_H = "https://raw.githubusercontent.com/torvalds/linux/master/include/linux/syscalls.h"
PROTO = re.compile(r"asmlinkage\s+long\s+sys_(\w+)\s*\(([^;]*)\);", re.S)
MAX_ARGS = 6
# Prototype names that leak types or predate current names, plus syscalls whose
# kernel prototypes leave args unnamed. Strace-flavored names.
ALIASES = {"mmap_pgoff": "mmap"}
TYPE_WORDS = {
    "void", "char", "short", "int", "long", "float", "double", "signed", "unsigned",
    "struct", "union", "enum", "const", "volatile", "bool", "size_t", "ssize_t",
}
OVERRIDES = {
    "socket": ("domain", "type", "protocol"),
    "socketpair": ("domain", "type", "protocol", "sv"),
    "bind": ("fd", "addr", "len"),
    "connect": ("fd", "addr", "len"),
    "listen": ("fd", "backlog"),
    "accept": ("fd", "addr", "addrlen"),
    "accept4": ("fd", "addr", "addrlen", "flags"),
    "getsockname": ("fd", "addr", "addrlen"),
    "getpeername": ("fd", "addr", "addrlen"),
    "setsockopt": ("fd", "level", "optname", "optval", "optlen"),
    "getsockopt": ("fd", "level", "optname", "optval", "optlen"),
    "shutdown": ("fd", "how"),
    "sendto": ("fd", "buf", "len", "flags", "addr", "addrlen"),
    "recvfrom": ("fd", "buf", "len", "flags", "addr", "addrlen"),
    "sendmsg": ("fd", "msg", "flags"),
    "recvmsg": ("fd", "msg", "flags"),
    "pipe": ("fds",),
    "pipe2": ("fds", "flags"),
    "dup": ("oldfd",),
    "dup2": ("oldfd", "newfd"),
    "dup3": ("oldfd", "newfd", "flags"),
    "openat": ("dirfd", "path", "flags", "mode"),
    "openat2": ("dirfd", "path", "how", "size"),
}


def parse(path):
    """Return {number: name}; direct integer defines win over 3264 aliases."""
    direct = {}
    alias = []
    for line in Path(path).read_text().splitlines():
        if m := INT.match(line):
            name, number = m.group(1), int(m.group(2))
            if name != "syscalls":
                direct[number] = name
        elif m := ALIAS.match(line):
            alias.append(m.groups())
    result = dict(direct)
    for name, target in alias:
        numbers = [n for n, existing in direct.items() if existing == target]
        if numbers:
            result.setdefault(numbers[0], name)  # direct defines win over aliases
    return result


def arg_names(header):
    """Parse sys_foo(...) prototypes into {name: (arg names, at most 6)}."""
    table = {}
    for name, params in PROTO.findall(header):
        params = " ".join(params.split())
        if not params or params == "void":
            table[name] = ()
            continue
        names = []
        for p in params.split(","):
            p = re.sub(r"\[[^\]]*\]\s*$", "", p.strip())  # drop array suffixes
            m = re.search(r"(\w+)\s*$", p)
            word = m.group(1) if m else ""
            if word in TYPE_WORDS or word.endswith("_t"):  # unnamed in the kernel
                word = ""
            names.append(word or f"arg{len(names)}")
        table[name] = tuple(names[:MAX_ARGS])
    for old, new in ALIASES.items():
        if old in table:
            table[new] = table.pop(old)
    table.update(OVERRIDES)
    return table


def fetch_syscall_prototypes():
    request = urllib.request.Request(SYSCALLS_H, headers={"User-Agent": "hisstrace-table-gen"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode()


def emit(arch, table, out):
    out.append(f"{arch} = {{")
    for number, name in sorted(table.items()):
        out.append(f'    {number}: "{name}",')
    out.append("}")
    out.append("")


def emit_args(table, out):
    out.append("ARGS = {")
    for name in sorted(table):
        args = ", ".join(f'"{a}"' for a in table[name])
        out.append(f'    "{name}": ({args}),')
    out.append("}")
    out.append("")


def main():
    amd64 = parse("/usr/include/x86_64-linux-gnu/asm/unistd_64.h")
    aarch64 = parse("/usr/include/asm-generic/unistd.h")
    args = arg_names(fetch_syscall_prototypes())
    out = ["# Generated by generate_table.py. Do not edit.", ""]
    emit("AMD64", amd64, out)
    emit("AARCH64", aarch64, out)
    emit_args(args, out)
    out.append('TABLES = {"x86_64": AMD64, "aarch64": AARCH64}')
    out.append("")
    Path("src/hisstrace/table.py").write_text("\n".join(out))
    print(f"amd64: {len(amd64)} syscalls, aarch64: {len(aarch64)} syscalls, args: {len(args)} syscalls")


if __name__ == "__main__":
    main()
